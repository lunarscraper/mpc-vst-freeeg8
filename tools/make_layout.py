#!/usr/bin/env python3
"""Writes vst/layout.conf (run from anywhere: python3 tools/make_layout.py).
Two band pages (4 bands each, one column per band) and a MASTER page. MPC skins can't draw curves, so the page
shows large values instead, and the Q-Links follow the columns: knob 1/2 = band 1 FREQ/GAIN, 3/4 = band 2 ...,
second Q-Link bank = each band's Q under its FREQ knob. Switches and selectors stay off the Q-Links."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "vst", "layout.conf")

THEME = """# Free EQ8 -- generated by tools/make_layout.py, edit that instead
theme_bg=1b2026
theme_panel=232a31
theme_line=3a4550
theme_ink=e8eef2
theme_ink_dim=8fa3b0
theme_ink_faint=56656f
theme_accent=29c5e6
theme_accent_hi=6fe3f7
theme_knob_face=2e3740
theme_knob_ring=4a5866
theme_knob_dot=29c5e6
theme_bar=12171c
theme_btn_text=e8eef2
theme_tab_on=29c5e6
theme_tab_on_tx=0d1418
theme_lcd=12171c
theme_seg_active=29c5e6
theme_seg_inactive=2b333b
theme_seg_active_tx=0d1418
theme_box=232a31
label_scale=1.3
scale_names=1
art_css=skin.css
"""

# option indices of b<n>_type (names have spaces, which when= can't take): BELL, LOW SHELF, HIGH SHELF / LOW CUT, HIGH CUT
GAIN_TYPES = [0, 1, 2]
CUT_TYPES = [3, 4]
TYPE_LABELS = "BELL,LO SHELF,HI SHELF,LO CUT,HI CUT,BAND"


def band_column(b, col):
    x0 = 18 + col * 314
    cx = x0 + 150
    L = []
    L.append('frame x=%d y=96 w=300 h=612 title="BAND %d"' % (x0, b))
    L.append('toggle cx=%d cy=128 label="" key=b%d_on ns=0 bw=90' % (x0 + 250, b))
    # all six types on screen (3 x 2): a tap picks one, no pop-up list over the knobs
    L.append('enum_h cx=%d cy=206 label="" key=b%d_type sw=96 sh=46 rows=2 options="%s"' % (cx, b, TYPE_LABELS))
    L.append('knob cx=%d cy=362 r=58 label="FREQ" key=b%d_freq ns=24 vs=32 bw=260' % (cx, b))
    for t in GAIN_TYPES:
        L.append('knob cx=%d cy=590 r=44 label="GAIN" key=b%d_gain ns=22 vs=28 bw=140 when=b%d_type:%d'
                 % (x0 + 78, b, b, t))
    for t in CUT_TYPES:
        L.append('enum_v cx=%d cy=596 label="" key=b%d_slope sw=124 sh=44 options="12 dB,24 dB,48 dB" when=b%d_type:%d' % (x0 + 78, b, b, t))
    L.append('knob cx=%d cy=590 r=44 label="Q" key=b%d_q ns=22 vs=28 bw=140' % (x0 + 224, b))
    return L


def band_tab(first):
    bands = range(first, first + 4)
    L = ["", "[tab BANDS %d-%d]" % (first, first + 3)]
    for col, b in enumerate(bands):
        L += band_column(b, col)
    keys = []
    for b in bands:
        keys += ["b%d_freq" % b, "b%d_gain" % b]
    for b in bands:
        keys += ["b%d_q" % b, "-"]
    L.append('qlinks "BANDS %d-%d" = %s' % (first, first + 3, ",".join(keys)))
    return L


def master_tab():
    L = ["", "[tab MASTER]"]
    L.append('frame x=18 y=96 w=1244 h=170 title="BANDS ON / OFF"')
    for b in range(1, 9):
        L.append('toggle cx=%d cy=190 label="%d" key=b%d_on bw=140' % (96 + (b - 1) * 155, b, b))
    L.append('frame x=18 y=282 w=1244 h=170 title="LISTEN: HEAR ONE BAND ALONE"')
    L.append('enum_h cx=640 cy=380 label="" key=listen sw=124 sh=64 rows=1')
    L.append('frame x=18 y=468 w=1244 h=240 title="OUTPUT"')
    L.append('knob cx=330 cy=570 r=58 label="OUTPUT" key=out ns=24 vs=32 bw=260')
    L.append('knob cx=760 cy=570 r=58 label="SCALE" key=scale ns=24 vs=32 bw=260')
    L.append('qlinks "MASTER" = out,scale,listen')
    return L


if __name__ == "__main__":
    lines = THEME.rstrip("\n").split("\n") + ["qlinks_track = b1_freq,b1_gain,b2_freq,b2_gain,b3_freq,b3_gain,b4_freq,b4_gain"]
    lines += band_tab(1) + band_tab(5) + master_tab()
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT))
